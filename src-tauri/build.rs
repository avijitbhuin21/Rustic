use std::fs;
use std::path::Path;

const HANDLER_SOURCE: &str = "src/lib.rs";
const HANDLER_MACRO: &str = "tauri::generate_handler![";
const PERMISSION_FILE: &str = "permissions/app-commands.toml";

/// Command names registered in the `generate_handler!` list of `src/lib.rs`.
fn registered_commands() -> Vec<String> {
    let source = fs::read_to_string(HANDLER_SOURCE)
        .unwrap_or_else(|e| panic!("cannot read {HANDLER_SOURCE}: {e}"));
    let start = source
        .find(HANDLER_MACRO)
        .unwrap_or_else(|| panic!("{HANDLER_MACRO} not found in {HANDLER_SOURCE}"))
        + HANDLER_MACRO.len();
    let end = source[start..]
        .find(']')
        .unwrap_or_else(|| panic!("unterminated {HANDLER_MACRO} in {HANDLER_SOURCE}"))
        + start;

    let mut commands = Vec::new();
    for line in source[start..end].lines() {
        let line = line.split("//").next().unwrap_or("").trim();
        for entry in line.split(',') {
            let name = entry.trim().rsplit("::").next().unwrap_or("").trim();
            if name.is_empty() {
                continue;
            }
            assert!(
                name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'),
                "unexpected entry {entry:?} in the {HANDLER_MACRO} list; build.rs only understands plain command paths"
            );
            commands.push(name.to_string());
        }
    }
    // An empty list would produce no app manifest, and Tauri then leaves every
    // app command callable from any origin.
    assert!(
        !commands.is_empty(),
        "no commands found in the {HANDLER_MACRO} list"
    );
    commands.sort();
    commands.dedup();
    commands
}

/// Write the app permission that allows every registered command, so Tauri
/// enforces its ACL on app commands and only capabilities that list it can call them.
fn write_app_permission(commands: &[String]) {
    let mut toml = String::from(
        "# Generated by build.rs from the generate_handler! list in src/lib.rs. Do not edit.\n\
         # Its presence makes Tauri check the ACL for app commands: only windows and\n\
         # origins named by a capability that lists `app-commands` can invoke them.\n\n\
         [[permission]]\n\
         identifier = \"app-commands\"\n\
         description = \"Every Rustic desktop command. Grant to the local app window only.\"\n\
         commands.allow = [\n",
    );
    for command in commands {
        toml.push_str(&format!("  \"{command}\",\n"));
    }
    toml.push_str("]\n");

    let path = Path::new(PERMISSION_FILE);
    if fs::read_to_string(path).ok().as_deref() == Some(toml.as_str()) {
        return;
    }
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).unwrap_or_else(|e| panic!("cannot create {}: {e}", dir.display()));
    }
    fs::write(path, toml).unwrap_or_else(|e| panic!("cannot write {PERMISSION_FILE}: {e}"));
}

fn main() {
    println!("cargo:rerun-if-changed={HANDLER_SOURCE}");
    write_app_permission(&registered_commands());
    tauri_build::build()
}
